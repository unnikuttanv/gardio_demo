"""Pydantic contracts shared across layers.

`FeatureSet` is the boundary between the deterministic half (signal/, features/)
and the generative half (report/). `EcgReport` is the pipeline's final output.
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class EcgSignal(BaseModel):
    """A loaded ECG recording (single lead used downstream)."""

    values: list[float] = Field(..., description="Amplitude samples (mV).")
    fs: int = Field(..., description="Sampling frequency in Hz.")
    lead: str = Field("II", description="Lead name.")
    source: str = Field("synthetic", description="Where the record came from.")

    @property
    def duration_s(self) -> float:
        return len(self.values) / self.fs if self.fs else 0.0


class FeatureSet(BaseModel):
    """Interpreted features handed to the LLM — numbers plus rule-based flags."""

    # Provenance
    source: str
    lead: str
    fs: int
    duration_s: float

    # Rhythm
    n_beats: int
    mean_hr_bpm: float
    min_hr_bpm: float
    max_hr_bpm: float

    # HRV (time-domain)
    sdnn_ms: float
    rmssd_ms: float
    pnn50_pct: float

    # Rule-based interpretation flags
    flags: list[str] = Field(default_factory=list)


class EcgReport(BaseModel):
    """Final clinical narrative plus the structured findings it was built from."""

    narrative: str
    findings: list[str]
    features: FeatureSet
    model: str
    is_mock: bool = Field(
        ...,
        description="True when generated by the deterministic mock, not a real model.",
    )


class DailyRecord(BaseModel):
    """One user's ECG features for one day of monitoring."""

    day_index: int = Field(..., description="0-based day within the monitoring window.")
    date: str = Field(..., description="ISO date (YYYY-MM-DD).")
    features: FeatureSet


class UserWeek(BaseModel):
    """A single monitored user: profile, per-day records, and an LLM weekly summary."""

    user_id: str
    name: str
    profile: str = Field(..., description="Short clinical persona, e.g. 'recovering patient'.")
    daily: list[DailyRecord]
    weekly_summary: str
    summary_model: str
    summary_is_mock: bool


class Cohort(BaseModel):
    """A multi-user, multi-day synthetic monitoring dataset for the demo."""

    generated_at: str
    n_days: int
    users: list[UserWeek]

"""Gradio demo — the HuggingFace Spaces entrypoint.

Two tabs:
  * Single recording — generate one ECG, run the full pipeline, show signal +
    features + LLM narrative.
  * Cohort dashboard — a multi-user, multi-day monitoring view with per-user
    trend charts, daily features, and an LLM weekly summary.
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

import gradio as gr  # noqa: E402

from ecg_llm.cohort import (  # noqa: E402
    DEFAULT_COHORT_PATH,
    generate_cohort,
    load_cohort,
    save_cohort,
)
from ecg_llm.features import build_features  # noqa: E402
from ecg_llm.ingest import generate_synthetic_ecg  # noqa: E402
from ecg_llm.report import generate_report  # noqa: E402
from ecg_llm.schemas import Cohort, UserWeek  # noqa: E402
from ecg_llm.signal import clean, detect_rpeaks  # noqa: E402

# ---------------------------------------------------------------- single tab


def _plot(signal, fs, rpeaks):
    seconds = min(10, len(signal) / fs)  # show first 10 s
    n = int(seconds * fs)
    t = [i / fs for i in range(n)]
    fig, ax = plt.subplots(figsize=(9, 3))
    ax.plot(t, signal[:n], linewidth=0.8, color="#1f77b4")
    peaks_in_window = [p for p in rpeaks if p < n]
    ax.scatter([p / fs for p in peaks_in_window], [signal[p] for p in peaks_in_window],
               color="#d62728", s=18, zorder=3, label="R peaks")
    ax.set_xlabel("Time (s)")
    ax.set_ylabel("Amplitude (mV)")
    ax.set_title("ECG (first 10 s) with detected R peaks")
    ax.legend(loc="upper right")
    fig.tight_layout()
    return fig


def analyze(duration_s: float, mean_hr_bpm: float):
    sig = generate_synthetic_ecg(duration_s=duration_s, mean_hr_bpm=mean_hr_bpm)
    filtered = clean(sig.values, sig.fs)
    rpeaks = detect_rpeaks(filtered, sig.fs)
    features = build_features(sig)
    report = generate_report(features)

    fig = _plot(filtered, sig.fs, rpeaks)
    feature_md = "\n".join(f"- **{k}**: {v}" for k, v in features.model_dump().items())
    tag = "🤖 mock" if report.is_mock else f"✅ {report.model}"
    narrative = f"_Generated by: {tag}_\n\n{report.narrative}"
    return fig, feature_md, narrative


# ---------------------------------------------------------------- cohort tab


def _load_or_none() -> Cohort | None:
    try:
        return load_cohort(DEFAULT_COHORT_PATH)
    except (FileNotFoundError, ValueError):
        return None


def _user_choices(cohort: Cohort | None) -> list[str]:
    if not cohort:
        return []
    return [f"{u.user_id} — {u.name}" for u in cohort.users]


def _find_user(cohort: Cohort, label: str) -> UserWeek | None:
    uid = label.split(" — ", 1)[0]
    return next((u for u in cohort.users if u.user_id == uid), None)


def _overview_md(cohort: Cohort | None) -> str:
    if not cohort:
        return (
            "⚠️ No cohort dataset found. Click **Regenerate cohort** below "
            "(runs the DSP pipeline + one LLM summary per user)."
        )
    rows = [
        "| User | Profile | HR start→end | SDNN start→end | LLM |",
        "|------|---------|--------------|----------------|-----|",
    ]
    for u in cohort.users:
        hr0, hr1 = u.daily[0].features.mean_hr_bpm, u.daily[-1].features.mean_hr_bpm
        s0, s1 = u.daily[0].features.sdnn_ms, u.daily[-1].features.sdnn_ms
        tag = "🤖 mock" if u.summary_is_mock else "✅ live"
        rows.append(
            f"| {u.user_id} {u.name} | {u.profile} | "
            f"{hr0:.0f}→{hr1:.0f} bpm | {s0:.0f}→{s1:.0f} ms | {tag} |"
        )
    header = (
        f"**Cohort:** {len(cohort.users)} users × {cohort.n_days} days "
        f"· generated {cohort.generated_at}\n\n"
    )
    return header + "\n".join(rows)


def _trend_plot(user: UserWeek):
    dates = [r.date[5:] for r in user.daily]  # MM-DD
    hr = [r.features.mean_hr_bpm for r in user.daily]
    sdnn = [r.features.sdnn_ms for r in user.daily]

    fig, ax1 = plt.subplots(figsize=(9, 3.4))
    ax1.plot(dates, hr, marker="o", color="#d62728", label="Mean HR (bpm)")
    ax1.set_ylabel("Mean HR (bpm)", color="#d62728")
    ax1.tick_params(axis="y", labelcolor="#d62728")
    ax1.set_xlabel("Date")

    ax2 = ax1.twinx()
    ax2.plot(dates, sdnn, marker="s", color="#1f77b4", label="SDNN (ms)")
    ax2.set_ylabel("SDNN (ms)", color="#1f77b4")
    ax2.tick_params(axis="y", labelcolor="#1f77b4")

    ax1.set_title(f"{user.user_id} {user.name} — {user.profile}")
    fig.tight_layout()
    return fig


def _daily_table_md(user: UserWeek) -> str:
    rows = [
        "| Date | HR (bpm) | min–max | SDNN | RMSSD | pNN50 | Flags |",
        "|------|----------|---------|------|-------|-------|-------|",
    ]
    for r in user.daily:
        f = r.features
        flags = ", ".join(f.flags) if f.flags else "—"
        rows.append(
            f"| {r.date} | {f.mean_hr_bpm:.0f} | {f.min_hr_bpm:.0f}–{f.max_hr_bpm:.0f} "
            f"| {f.sdnn_ms:.0f} | {f.rmssd_ms:.0f} | {f.pnn50_pct:.0f}% | {flags} |"
        )
    return "\n".join(rows)


def view_user(label: str):
    cohort = _load_or_none()
    if not cohort or not label:
        return None, "", ""
    user = _find_user(cohort, label)
    if not user:
        return None, "", ""
    tag = "🤖 mock" if user.summary_is_mock else f"✅ {user.summary_model}"
    summary = f"### Weekly summary\n_Generated by: {tag}_\n\n{user.weekly_summary}"
    return _trend_plot(user), _daily_table_md(user), summary


def regenerate_cohort():
    """Regenerate the cohort live (DSP + one LLM summary per user) and save."""
    cohort = generate_cohort(n_users=5, n_days=7)
    save_cohort(cohort, DEFAULT_COHORT_PATH)
    choices = _user_choices(cohort)
    first = choices[0] if choices else None
    plot, table, summary = view_user(first) if first else (None, "", "")
    return (
        _overview_md(cohort),
        gr.update(choices=choices, value=first),
        plot,
        table,
        summary,
    )


# ---------------------------------------------------------------- layout

_initial_cohort = _load_or_none()
_initial_choices = _user_choices(_initial_cohort)
_initial_user = _initial_choices[0] if _initial_choices else None

with gr.Blocks(title="ECG-LLM-Analyst") as demo:
    gr.Markdown(
        "# 🫀 ECG-LLM-Analyst\n"
        "Classical signal processing (Pan-Tompkins + HRV) → LLM clinical narrative.\n"
        "_Set `GROQ_API_KEY` to use Groq; otherwise a deterministic mock is used._"
    )

    with gr.Tab("Single recording"):
        with gr.Row():
            duration = gr.Slider(10, 60, value=30, step=5, label="Duration (s)")
            hr = gr.Slider(40, 140, value=72, step=2, label="Target mean HR (bpm)")
        run_btn = gr.Button("Analyze", variant="primary")
        plot = gr.Plot(label="ECG")
        with gr.Row():
            features_box = gr.Markdown(label="Features")
            narrative_box = gr.Markdown(label="Narrative report")
        run_btn.click(analyze, inputs=[duration, hr],
                      outputs=[plot, features_box, narrative_box])

    with gr.Tab("Cohort dashboard"):
        gr.Markdown("### Multi-user, multi-day monitoring")
        overview = gr.Markdown(_overview_md(_initial_cohort))
        with gr.Row():
            user_dd = gr.Dropdown(
                choices=_initial_choices, value=_initial_user, label="Select patient"
            )
            regen_btn = gr.Button("Regenerate cohort (live LLM)", variant="secondary")
        trend = gr.Plot(label="HR & HRV trend")
        daily_tbl = gr.Markdown()
        weekly = gr.Markdown()

        user_dd.change(view_user, inputs=[user_dd], outputs=[trend, daily_tbl, weekly])
        regen_btn.click(
            regenerate_cohort,
            outputs=[overview, user_dd, trend, daily_tbl, weekly],
        )

        # Populate the first user's view on load.
        if _initial_user:
            demo.load(
                lambda: view_user(_initial_user),
                outputs=[trend, daily_tbl, weekly],
            )


if __name__ == "__main__":
    demo.launch(server_name="0.0.0.0", server_port=7860)
